# Geom groups (viewer toggles 0-5).
G_PHYSICAL, G_REFERENCE, G_VISUAL, G_ENVELOPE, G_PROXY, G_GUARD = 0, 1, 2, 3, 4, 5
REFERENCE_CATEGORIES = {"floor", "aisle"}
ENVELOPE_ALPHA, GUARD_ALPHA, PROXY_ALPHA = 0.12, 0.25, 0.4

# PLACEHOLDER actuator gains: enough for the viewer's sliders to move a joint, not a motion model.
KP_HINGE, KV_HINGE = 2000.0, 200.0     # N m / rad, N m s / rad
KP_SLIDE, KV_SLIDE = 20000.0, 2000.0   # N / m, N s / m
MIN_PIECE = 1e-6                       # m: a box piece thinner than this is dropped


class ExportError(Exception):
    def __init__(self, errors: list[str]):
        super().__init__("; ".join(errors))
        self.errors = errors


# ---------------------------------------------------------------- small geometry

def quat_z(yaw: float) -> list[float]:
    return [math.cos(yaw / 2.0), 0.0, 0.0, math.sin(yaw / 2.0)]


def to_local(p, frame) -> list[float]:
    """World point `p` in the frame (x, y, z, yaw) of a body."""
    dx, dy, dz = p[0] - frame[0], p[1] - frame[1], p[2] - frame[2]
    c, s = math.cos(-frame[3]), math.sin(-frame[3])
    return [c * dx - s * dy, s * dx + c * dy, dz]


def subtract(box, cut) -> list:
    """Axis-aligned box minus box: the pieces left, each (lo, hi)."""
    lo, hi = list(box[0]), list(box[1])
    if any(hi[i] <= cut[0][i] or lo[i] >= cut[1][i] for i in range(3)):
        return [box]
    out = []
    for i in range(3):
        if lo[i] < cut[0][i]:
            out.append((list(lo), [*hi[:i], cut[0][i], *hi[i + 1:]]))
            lo[i] = cut[0][i]
        if hi[i] > cut[1][i]:
            out.append(([*lo[:i], cut[1][i], *lo[i + 1:]], list(hi)))
            hi[i] = cut[1][i]
    return [b for b in out if all(b[1][i] - b[0][i] > MIN_PIECE for i in range(3))]


def box_pieces(it: layout.Item) -> list:
    """A layout box with its hollow and cuts taken out, as (lo, hi) boxes in the line frame."""
    c = [d.value for d in it.centre]
    s = [d.value for d in it.size]
    boxes = [([c[i] - s[i] / 2.0 for i in range(3)], [c[i] + s[i] / 2.0 for i in range(3)])]
    cutters = []
    if it.hollow:
        h = [it.hollow[0].value, it.hollow[1].value]
        cutters.append(([c[0] - h[0] / 2.0, c[1] - h[1] / 2.0, c[2] - s[2]],
                        [c[0] + h[0] / 2.0, c[1] + h[1] / 2.0, c[2] + s[2]]))
    for cc, cs in it.cuts:
        cc, cs = [d.value for d in cc], [d.value for d in cs]
        cutters.append(([cc[i] - cs[i] / 2.0 for i in range(3)],
                        [cc[i] + cs[i] / 2.0 for i in range(3)]))
    for cut in cutters:
        boxes = [p for b in boxes for p in subtract(b, cut)]
    return boxes


# ---------------------------------------------------------------- naming

def item_key(it: layout.Item) -> str:
    """The geom name an item's geoms carry. Two layout solids share `Scara_<S>_Base` (the
    pedestal and the vendor base housing): the housing is `Scara_<S>_Housing`; the vendor's
    Link2_<k> solids are one capsule, `Scara_<S>_Link2`."""
    if it.subgroup and it.subgroup.startswith("Scara_") and it.solid is not None:
        role = it.name.removeprefix(it.subgroup + "_")
        if role == "Base":
            return f"{it.subgroup}_Housing"
        if re.fullmatch(r"Link2_\d+", role):
            return f"{it.subgroup}_Link2"
    return it.name


def _prefixes(raw: dict) -> list[tuple[str, str, str]]:
    """(layout name prefix, spec id, kind), longest prefix first."""
    out = []
    for sid in raw.get("stations") or {}:
        out.append((f"Station_{pascal(sid.removeprefix('st_'))}", sid, "station"))
    for sid in scara_ids(raw):
        out.append((f"Scara_{pascal(sid.removeprefix('scara_'))}", sid, "scara"))
    for hid in raw.get("gang_heads") or {}:
        out.append((f"GangHead_{pascal(hid.removeprefix('gh_'))}", hid, "gang_head"))
    for fid in raw.get("feeders") or {}:
        out.append((f"Feeder_{pascal(fid.removeprefix('fd_'))}", fid, "feeder"))
    for bid in raw.get("buffers") or {}:
        out.append((f"Buffer_{pascal(bid.removeprefix('buf_'))}", bid, "buffer"))
    for rid in raw.get("return_paths") or {}:
        p = pascal(rid.removeprefix("rt_"))
        out.append((f"ReturnPath_{p}", rid, "return"))
        out.append((f"ReturnSink_{p}", rid, "return"))
    return sorted(out, key=lambda t: -len(t[0]))


def owner_of(name: str, prefixes) -> tuple[str, str] | None:
    """(spec id, kind) of the entity a layout solid belongs to, or None (a layout-named body)."""
    for prefix, eid, kind in prefixes:
        if name == prefix or name.startswith(prefix + "_"):
            return eid, kind
    return None


# ---------------------------------------------------------------- the export

@dataclass
class Export:
    spec: mujoco.MjSpec
    items: list
    line: LineSpec
    values: Values
    keys: dict = field(default_factory=dict)        # geom key -> {category, body, group}
    bodies: dict = field(default_factory=dict)      # spec-ID body -> {kind, pose}
    keyframes: dict = field(default_factory=dict)   # name -> {joint: value}
    meshes: list = field(default_factory=list)      # (mesh name, source STL, file name)
    warnings: list = field(default_factory=list)


def rgba(category: str, alpha: float = 1.0) -> list[float]:
    return [*layout.colour_of(category), alpha]


def _flags(g, category: str, group: int) -> None:
    g.group = group
    if group in (G_ENVELOPE, G_VISUAL):
        g.contype = g.conaffinity = 0
    alpha = (ENVELOPE_ALPHA if group == G_ENVELOPE else PROXY_ALPHA if group == G_PROXY
             else GUARD_ALPHA if category == "guard" else 1.0)
    g.rgba = rgba(category, alpha)


def add_box(body, name, centre, size, frame, yaw_w, category, group):
    g = body.add_geom(name=name, type=mujoco.mjtGeom.mjGEOM_BOX,
                      size=[size[0] / 2.0, size[1] / 2.0, size[2] / 2.0],
                      pos=to_local(centre, frame), quat=quat_z(yaw_w - frame[3]))
    _flags(g, category, group)
    return g


def add_cylinder(body, name, centre, radius, height, frame, category, group, local=False):
    g = body.add_geom(name=name, type=mujoco.mjtGeom.mjGEOM_CYLINDER,
                      size=[radius, height / 2.0, 0.0],
                      pos=list(centre) if local else to_local(centre, frame))
    _flags(g, category, group)
    return g


def add_stadium(body, key, a, b, radius, z0, z1, category="robot"):
    """robot_geometry's capsule in the body frame: plan segment a->b (z = 0 plane) ± radius,
    over z0..z1 — a box along the segment and a cylinder at each end."""
    dx, dy = b[0] - a[0], b[1] - a[1]
    length = math.hypot(dx, dy)
    zc, h = (z0 + z1) / 2.0, z1 - z0
    geoms = []
    k = 0
    if length > MIN_PIECE:
        g = body.add_geom(name=f"{key}__{k}", type=mujoco.mjtGeom.mjGEOM_BOX,
                          size=[length / 2.0, radius, h / 2.0],
                          pos=[(a[0] + b[0]) / 2.0, (a[1] + b[1]) / 2.0, zc],
                          quat=quat_z(math.atan2(dy, dx)))
        _flags(g, category, G_PHYSICAL)
        geoms.append(g)
        k += 1
    for p in ((a, b) if length > MIN_PIECE else (a,)):
        g = body.add_geom(name=f"{key}__{k}", type=mujoco.mjtGeom.mjGEOM_CYLINDER,
                          size=[radius, h / 2.0, 0.0], pos=[p[0], p[1], zc])
        _flags(g, category, G_PHYSICAL)
        geoms.append(g)
        k += 1
    return geoms


def add_item(ex: Export, body, it: layout.Item, frame) -> None:
    """One layout solid as primitives on `body` (whose world pose is `frame`)."""
    key = item_key(it)
    cat = it.category
    group = (G_ENVELOPE if cat == "envelope" else G_GUARD if cat == "guard"
             else G_REFERENCE if cat in REFERENCE_CATEGORIES
             else G_PROXY if cat == "carrier" else G_PHYSICAL)
    ex.keys[key] = {"category": cat, "body": body.name, "group": group}
    c = [d.value for d in it.centre]
    s = [d.value for d in it.size]
    if it.cylinder:
        if it.cuts:
            raise ExportError([f"{it.name}: a cylinder with cuts has no primitive form"])
        if it.hollow and cat != "envelope":
            raise ExportError([f"{it.name}: a hollow cylinder that is not an envelope has no "
                               "convex form"])
        add_cylinder(body, key, c, s[0] / 2.0, s[2], frame, cat, group)
        return
    yaw = it.yaw.value if it.yaw is not None else 0.0
    if it.hollow or it.cuts:
        if yaw:
            raise ExportError([f"{it.name}: a hollow or cut box with a yaw is not split"])
        for k, (lo, hi) in enumerate(box_pieces(it)):
            add_box(body, f"{key}__{k}", [(lo[i] + hi[i]) / 2.0 for i in range(3)],
                    [hi[i] - lo[i] for i in range(3)], frame, 0.0, cat, group)
        return
    add_box(body, key, c, s, frame, yaw, cat, group)


def entity_pose(line: LineSpec, eid: str, kind: str) -> tuple[float, float, float, float]:
    """The resolved spec pose of a spec-ID body (x, y, z, yaw); yaw 0 when it has none."""
    if kind == "station":
        p = line.stations[eid].pose
    elif kind == "feeder":
        p = line.feeders[eid].pose
    elif kind == "buffer":
        p = line.buffers[eid].pose
    elif kind == "return":
        p = line.return_paths[eid].pose
    elif kind == "gang_head":
        h = line.gang_heads[eid]
        p = h.pose or line.stations[rg.head_box(line, eid, rg.CadHeights()).station].pose
    else:
        raise KeyError(kind)
    p = list(p) + [None] * (4 - len(p))
    if None in p[:3]:
        raise ExportError([f"{eid}: resolved pose {p} has a null"])
    return float(p[0]), float(p[1]), float(p[2]), float(p[3] or 0.0)


def build(merged, dev: bool, cad_reports: Path | None = None) -> Export:
    """The MjSpec of `merged` (a spec.Merged, possibly a station subset). Raises ExportError."""
    line = parse_spec(merged.raw)
    if line.layout is None:
        raise ExportError(["the spec has no `layout:` section"])
    v = Values(merged.raw, {p["path"] for p in merged.placeholders})
    cad = rg.CadHeights(cad_reports, dev)
    notes: dict = {"warnings": [], "vendor": {}}
    items = layout.plan(v, line, cad, notes)
    if items is None:
        raise ExportError([f"no value for: {m}" for m in sorted(set(v.missing))])

    s = mujoco.MjSpec()
    s.modelname = "drone_line" + (".dev" if dev else "")
    s.compiler.degree = False
    s.compiler.autolimits = True
    s.option.gravity = [0.0, 0.0, 0.0]          # kinematic: physics is a later milestone
    # The shaft's inertia about J4 is ~1.6e-4 kg m^2: explicit Euler with the PLACEHOLDER kv below
    # diverges within two steps (QACC NaN at the j4 DOF, M1 benchmark). implicitfast integrates the
    # actuators' velocity damping implicitly, so the sliders stay stable (3.12-compatible).
    s.option.integrator = mujoco.mjtIntegrator.mjINT_IMPLICITFAST
    s.visual.global_.offwidth, s.visual.global_.offheight = 1600, 1000
    s.visual.headlight.ambient = [0.45, 0.45, 0.45]
    s.visual.headlight.diffuse = [0.55, 0.55, 0.55]
    s.visual.map.zfar = 200.0               # renders from far overhead (check_mjcf_match)
    s.worldbody.add_light(name="sun", pos=[0.0, 0.0, 4.0], dir=[0.3, 0.2, -1.0],
                          type=mujoco.mjtLightType.mjLIGHT_DIRECTIONAL)
    ex = Export(s, items, line, v, warnings=list(notes["warnings"]))
    prefixes = _prefixes(merged.raw)
    index_station = {line.stations[st].index: st for st in line.stations}

    spec_bodies: dict[str, object] = {}

    def entity_body(eid: str, kind: str):
        if eid not in spec_bodies:
            pose = entity_pose(line, eid, kind)
            b = s.worldbody.add_body(name=eid, pos=list(pose[:3]), quat=quat_z(pose[3]))
            spec_bodies[eid] = b
            ex.bodies[eid] = {"kind": kind, "pose": list(pose)}
            if kind == "station":
                half = line.layout.stop_unit_length / 2.0
                b.add_site(name=f"{eid}_in", pos=[-half, 0.0, 0.0])
                b.add_site(name=f"{eid}_out", pos=[half, 0.0, 0.0])
            else:
                b.add_site(name=f"{eid}_mount", pos=[0.0, 0.0, 0.0])
        return spec_bodies[eid], ex.bodies[eid]["pose"]

    scara_items: dict[str, list] = {}
    head_items: dict[str, list] = {}
    carriers: dict[str, list] = {}
    for it in items:
        own = owner_of(it.name, prefixes)
        if own is not None and own[1] == "scara":
            scara_items.setdefault(own[0], []).append(it)
        elif own is not None and own[1] == "gang_head":
            head_items.setdefault(own[0], []).append(it)
        elif own is not None:
            body, frame = entity_body(*own)
            add_item(ex, body, it, frame)
        elif it.category == "carrier":
            carriers.setdefault(it.subgroup or it.name, []).append(it)
        else:
            c = [d.value for d in it.centre]
            frame = (c[0], c[1], c[2], 0.0)
            body = s.worldbody.add_body(name=it.name, pos=c)
            add_item(ex, body, it, frame)

    for sub, its in carriers.items():
        _carrier(ex, sub, its, index_station, dev)
    joints: dict[str, dict] = {}
    for sid in scara_ids(merged.raw):
        _scara(ex, sid, scara_items.get(sid, []), cad, joints)
    for hid in sorted(merged.raw.get("gang_heads") or {}):
        if hid in head_items:
            body, frame = entity_body(hid, "gang_head")
            _gang_head(ex, hid, body, frame, head_items[hid], cad, joints)

    for jname, j in joints.items():
        a = s.add_actuator(name=jname, target=jname, trntype=mujoco.mjtTrn.mjTRN_JOINT)
        kp, kv = (KP_SLIDE, KV_SLIDE) if j["type"] == "slide" else (KP_HINGE, KV_HINGE)
        a.gaintype = mujoco.mjtGain.mjGAIN_FIXED
        a.biastype = mujoco.mjtBias.mjBIAS_AFFINE
        a.gainprm = [kp] + [0.0] * 9
        a.biasprm = [0.0, -kp, -kv] + [0.0] * 7
        a.ctrllimited = mujoco.mjtLimited.mjLIMITED_TRUE
        a.ctrlrange = list(j["range"])
    _keyframes(ex, joints)
    return ex


def _carrier(ex: Export, sub: str, its: list, index_station: dict, dev: bool) -> None:
    """A carrier at a station: body at the station's pallet datum (its STEP's rest plane), the
    generator's STL as a visual mesh, one collision box per layout solid."""
    m = re.fullmatch(r"(\w+?)_(\d+)", sub)
    part = next((p for p in layout.CARRIER_STEPS if pascal(p) == (m.group(1) if m else "")), None)
    st = index_station.get(int(m.group(2))) if m else None
    if part is None or st is None:
        raise ExportError([f"{sub}: cannot tell which carrier or station it is"])
    p = ex.line.stations[st].pose
    frame = (p[0], p[1], p[2], 0.0)
    body = ex.spec.worldbody.add_body(name=sub, pos=list(frame[:3]))
    stl = layout.CAD_OUT / ("dev" if dev else "") / layout.CARRIER_STEPS[part].replace(".step",
                                                                                       ".stl")
    if stl.is_file():
        mesh = f"mesh_{part}"
        if mesh not in {mm[0] for mm in ex.meshes}:   # 4.0: one asset defined once
            ex.meshes.append((mesh, stl, stl.name))
            ex.spec.add_mesh(name=mesh, file=stl.name, scale=[0.001] * 3)
        g = body.add_geom(name=f"{sub}_visual", type=mujoco.mjtGeom.mjGEOM_MESH, meshname=mesh)
        _flags(g, "carrier", G_VISUAL)
    else:
        ex.warnings.append(f"{sub}: {stl} not built; only its collision boxes are drawn")
    for it in its:
        add_item(ex, body, it, frame)
        g = ex.spec.geom(item_key(it))
        if not stl.is_file():
            g.group, g.rgba = G_PHYSICAL, rgba("carrier")


def _scara(ex: Export, sid: str, its: list, cad, joints: dict) -> None:
    k = rg.kin(ex.line, sid)
    model = ex.line.scaras[sid].model
    rm = ex.line.robot_models[model]
    caps = cad.vendor(model)
    errors = []
    if k is None or k.links is None:
        errors.append(f"{sid}: base pose or robot_models.{model}.link1/link2 is null")
    if caps is None:
        errors.append(f"{sid}: reports/vendor_{model}.json is missing (run tools/cad/layout.py "
                      f"or tools/cad/vendor.py <STEP> --model {model})")
    if errors:
        raise ExportError(errors)
    l1, l2 = k.links
    stroke = k.z_hi - k.z_lo
    frame = (k.base[0], k.base[1], k.base[2], k.yaw)
    s = ex.spec
    base = s.worldbody.add_body(name=sid, pos=list(k.base), quat=quat_z(k.yaw))
    ex.bodies[sid] = {"kind": "scara", "pose": list(frame)}
    name = f"Scara_{pascal(sid.removeprefix('scara_'))}"
    arm = {f"{name}_Link1", f"{name}_Link2", f"{name}_Shaft"}
    for it in its:
        key = item_key(it)
        if key in arm:
            continue                      # the vendor solids: drawn as capsules below
        if key == f"{name}_Housing":
            c, sz = [d.value for d in it.centre], [d.value for d in it.size]
            add_box(base, key, c, sz, frame, 0.0, "robot", G_PHYSICAL)   # its line-frame bbox
            ex.keys[key] = {"category": "robot", "body": sid, "group": G_PHYSICAL}
        else:
            add_item(ex, base, it, frame)
    shaft_bottom = caps["shaft_bottom_mm"] / 1000.0
    base.add_site(name=f"{sid}_mount", pos=[0.0, 0.0, k.z_hi - shaft_bottom - k.base[2]])
    top = stroke                          # TCP at the top of its stroke, base frame
    c = caps["capsules"]
    lim = rm.joint_limits

    def hinge(body, jn, limit):
        body.add_joint(name=jn, type=mujoco.mjtJoint.mjJNT_HINGE, axis=[0, 0, 1],
                       range=[-limit, limit])
        joints[jn] = {"type": "hinge", "range": (-limit, limit), "scara": sid}

    b1 = base.add_body(name=f"{sid}_link1")
    hinge(b1, f"{sid}_j1", lim.j1)
    add_stadium(b1, f"{name}_Link1", (0.0, 0.0), (l1, 0.0), c["link1"]["radius_m"],
                top + c["link1"]["z_m"][0], top + c["link1"]["z_m"][1])
    b2 = b1.add_body(name=f"{sid}_link2", pos=[l1, 0.0, 0.0])
    hinge(b2, f"{sid}_j2", lim.j2)
    b2.add_site(name=f"{sid}_elbow")
    add_stadium(b2, f"{name}_Link2", (0.0, 0.0), (l2, 0.0), c["link2"]["radius_m"],
                top + c["link2"]["z_m"][0], top + c["link2"]["z_m"][1])
    b3 = b2.add_body(name=f"{sid}_shaft", pos=[l2, 0.0, top])
    b3.add_joint(name=f"{sid}_j3", type=mujoco.mjtJoint.mjJNT_SLIDE, axis=[0, 0, 1],
                 range=[-stroke, 0.0])
    joints[f"{sid}_j3"] = {"type": "slide", "range": (-stroke, 0.0), "scara": sid}
    hinge(b3, f"{sid}_j4", lim.j4)
    z0, z1 = c["shaft"]["z_m"]
    add_cylinder(b3, f"{name}_Shaft", [0.0, 0.0, (z0 + z1) / 2.0], c["shaft"]["radius_m"],
                 z1 - z0, None, "robot", G_PHYSICAL, local=True)
    b3.add_site(name=f"{sid}_tcp")
    # One arm's capsules overlap at its joints (and link1 sits on the housing): no self-contact.
    arm_bodies = [sid, f"{sid}_link1", f"{sid}_link2", f"{sid}_shaft"]
    for i, a in enumerate(arm_bodies):
        for b in arm_bodies[i + 1:]:
            s.add_exclude(bodyname1=a, bodyname2=b)
    for key in arm:
        ex.keys[key] = {"category": "robot", "body": sid, "group": G_PHYSICAL}


def _gang_head(ex: Export, hid: str, body, frame, its: list, cad, joints: dict) -> None:
    hb = rg.head_box(ex.line, hid, cad)
    name = f"GangHead_{pascal(hid.removeprefix('gh_'))}"
    for it in its:
        if it.name != name:
            add_item(ex, body, it, frame)              # rail, post, slide envelope: static
    head = next((it for it in its if it.name == name), None)
    if head is None:
        return
    c = [d.value for d in head.centre]                # where it waits (layout.py draws it there)
    hbody = body.add_body(name=name, pos=to_local(c, frame), quat=quat_z(-frame[3]))
    if hb.slide_from:
        stroke = ex.line.gang_heads[hid].slide.stroke
        wy = (hb.working.y0 + hb.working.y1) / 2.0
        sign = 1.0 if wy > c[1] else -1.0             # towards the working position
        jn = f"{hid}_slide"
        hbody.add_joint(name=jn, type=mujoco.mjtJoint.mjJNT_SLIDE, axis=[0.0, sign, 0.0],
                        range=[0.0, stroke])
        joints[jn] = {"type": "slide", "range": (0.0, stroke), "head": hid,
                      "station": hb.station}
    add_item(ex, hbody, head, (c[0], c[1], c[2], 0.0))


def _keyframes(ex: Export, joints: dict) -> None:
    folded = {}
    for jn, j in joints.items():
        if "scara" in j:
            lim = ex.line.robot_models[ex.line.scaras[j["scara"]].model].joint_limits
            folded[jn] = lim.j2 if jn.endswith("_j2") else 0.0
        else:
            folded[jn] = 0.0
    ex.keyframes["folded"] = folded
    for sid in ex.line.scaras:
        if f"{sid}_j1" not in joints:
            continue
        pj = rg.park_joints(ex.line, sid)
        ends, starts = rg.park_steps(ex.line, sid)
        if pj is None or not (ends or starts):
            continue
        q = dict(folded)
        q[f"{sid}_j1"], q[f"{sid}_j2"] = pj
        st = ex.line.scaras[sid].station
        for jn, j in joints.items():
            if j.get("station") == st:
                q[jn] = j["range"][1]                  # the head in, working
        ex.keyframes[f"parked_{sid}"] = q


def compile_keys(ex: Export) -> mujoco.MjModel:
    """Compile once to learn the qpos layout, add the keyframes, compile again."""
    m = ex.spec.compile()
    for kname, q in ex.keyframes.items():
        qpos = [0.0] * m.nq
        ctrl = [0.0] * m.nu
        for jn, val in q.items():
            qpos[m.jnt_qposadr[m.joint(jn).id]] = val
            ctrl[m.actuator(jn).id] = val
        ex.spec.add_key(name=kname, qpos=qpos, ctrl=ctrl)
    return ex.spec.compile()


def output_name(name: str | None, dev: bool) -> str:
    return "line" + (f".{name}" if name else "") + (".dev" if dev else "") + ".xml"


def write(ex: Export, out: Path, dev: bool) -> dict:
    mesh_dir = out.parent / ("meshes/dev" if dev else "meshes")
    mesh_dir.mkdir(parents=True, exist_ok=True)
    for _, src, fname in ex.meshes:
        shutil.copyfile(src, mesh_dir / fname)
    ex.spec.meshdir = str(mesh_dir.relative_to(out.parent))
    ex.spec.modelfiledir = str(out.parent)
    m = compile_keys(ex)
    out.write_text(HEADER.format(dev=" + line_spec.dev.yaml (PLACEHOLDER values)" if dev else "")
                   + ex.spec.to_xml())
    return {"bodies": m.nbody, "geoms": m.ngeom, "joints": m.njnt, "actuators": m.nu,
            "sites": m.nsite, "keyframes": m.nkey, "meshes": m.nmesh}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate the line MJCF from the spec (M1)")
    ap.add_argument("--spec", type=Path, default=DEFAULT_SPEC)
    ap.add_argument("--stations", nargs="+", default=None,
                    help="export only these consecutive stations (spec.station_subset)")
    ap.add_argument("--name", default="batch", help="output/report name for --stations")
    ap.add_argument("--out-dir", type=Path, default=MJCF_DIR)
    ap.add_argument("--cad-reports", type=Path, default=None)
    add_dev_argument(ap)
    args = ap.parse_args(argv)
    stations = parse_station_list(args.stations)
    name = args.name if stations else None
    out = args.out_dir / output_name(name, args.dev)
    report = report_path(f"gen_mjcf.{name}" if name else "gen_mjcf", args.dev)
    doc: dict = {"passed": False, "dev": args.dev, "generator": "tools/gen_mjcf.py",
                 "mujoco": mujoco.__version__, "stations": stations, "output": str(out),
                 "placeholders": [], "missing": [], "warnings": [], "errors": []}

    def finish(code: int) -> int:
        doc["passed"] = code == 0
        report.parent.mkdir(parents=True, exist_ok=True)
        report.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n")
        for e in doc["errors"]:
            print(f"gen_mjcf: FAIL — {e}", file=sys.stderr)
        return code

    try:
        merged = load_merged(args.spec, args.dev)
        if stations:
            merged.raw = station_subset(merged.raw, stations)
        doc["placeholders"] = sorted({p["path"] for p in merged.placeholders})
        ex = build(merged, args.dev, args.cad_reports)
    except SpecError as exc:
        doc["errors"] = list(exc.errors)
        return finish(1)
    except ExportError as exc:
        doc["errors"] = exc.errors
        doc["missing"] = [e.removeprefix("no value for: ") for e in exc.errors
                          if e.startswith("no value for: ")]
        if doc["missing"] and not args.dev:
            doc["errors"].append("the base spec is not complete: fill the key(s) in, or re-run "
                                 "with --dev")
        return finish(1)
    try:
        args.out_dir.mkdir(parents=True, exist_ok=True)
        doc["counts"] = write(ex, out, args.dev)
    except (OSError, ValueError) as exc:
        doc["errors"].append(f"cannot write {out}: {exc}")
        return finish(1)
    doc["warnings"] += ex.warnings
    doc["bodies"] = ex.bodies
    doc["geom_keys"] = ex.keys
    doc["keyframes"] = sorted(ex.keyframes)
    doc["meshes"] = [str(src) for _, src, _ in ex.meshes]
    for w in doc["warnings"]:
        print(f"gen_mjcf: WARN {w}", file=sys.stderr)
    if args.dev:
        print(f"gen_mjcf: DEV MODE — {len(doc['placeholders'])} placeholder value(s); "
              f"{out.name} is not a deliverable")
    c = doc["counts"]
    print(f"gen_mjcf: OK — {c['bodies']} bodies, {c['geoms']} geoms, {c['joints']} joints, "
          f"{c['actuators']} actuators, {c['keyframes']} keyframes -> {out}")
    return finish(0)


if __name__ == "__main__":
    sys.exit(main())
