"""Generate the line as MuJoCo MJCF (M1), through MjSpec, from line_spec.yaml.

    tools/.venv/bin/python tools/gen_mjcf.py [--dev] [--stations IDS [--name N]] [--spec PATH]

There is no second layout here: every solid is one of tools/cad/layout.py's `plan()` items (the
same list the layout STEP, its interference check and its renders are built from), and every
SCARA's kinematics come from tools/robot_geometry.py's `kin()` and the vendor arm capsules
(reports/vendor_<model>.json). This file only says how each item becomes MuJoCo bodies and geoms.
Spec lengths are metres already (the layout STEP's millimetres are an export choice); only the
cad_out/ STL meshes are millimetres, scaled 0.001 here.

Bodies are named by spec ID where the thing has one — st_<station>, scara_<station>,
gh_<head>, fd_<feeder>, buf_<buffer>, rt_<return path> — and placed at that entity's resolved
pose (spec.resolve_anchors); M2 writes edits back through these names. Everything else (Floor,
Conveyor, Pallet_<n>, Pallet_Slot_<n>_<k>, carriers, guards, the aisle) is a body named after its
layout solid; those names can renumber when the spec changes (KNOWN_ISSUES). Geoms are named
after the layout solid they stand for (`<Solid>` or `<Solid>__<k>` when it takes several).
Sites: `<station>_in` / `<station>_out` (the stop unit's upstream / downstream edge on the
pallet datum plane), `<id>_mount` (a feeder, buffer, return path or gang head's spec pose),
`scara_<s>_mount` (the arm's mounting face), `scara_<s>_elbow` (J2) and `scara_<s>_tcp`.

Geom groups: 0 physical, 1 floor and aisle, 2 visual meshes, 3 envelopes, 4 carrier collision
boxes, 5 guards (fence, partitions) — all but 2 and 3 collide.

How an item becomes geoms:
  * a box or cylinder: the same primitive;
  * a hollow box or one with cuts (a queued-pallet outline, the fence, a partition): split into
    the boxes that remain, so MuJoCo's convex collision sees the opening (layout.py untouched);
  * an envelope (reach ring, slide sweep): visual only — contype = conaffinity = 0, geom group 3;
    the reach ring is drawn as its full cylinder, transparent;
  * a carrier: its generator's STL (cad_out/[dev/]) as a visual mesh (group 2, no contact), and
    one collision box per layout solid of it (group 4);
  * the Epson arm: J1/J2 hinges, J3 slide, J4 hinge (joint names scara_<s>_j1..j4, spec limits),
    each link the vendor capsule robot_geometry checks with — a plan stadium (segment ± radius)
    over its z range, as a box and two end cylinders — the shaft a cylinder; the pedestal
    (Scara_<S>_Base) and the vendor base housing (`Scara_<S>_Housing`, its layout bbox) are
    static on the SCARA body;
  * a gang head on a slide: a slide joint gh_<head>_slide from where it waits (0) to its working
    position (slide.stroke).
Contact between one SCARA's own bodies is excluded (its capsules overlap at the joints).
Every joint has a position actuator of the same name, so the viewer's sliders move it. Keyframes:
`folded` (every arm as layout.py draws it, j1 = 0, j2 at its limit, the TCP at the top of its
stroke, every head waiting) and `parked_<scara>` (that arm at its park_pose, its station's heads
working, the rest folded).

Fixed base, no physics tuning (a later milestone): gravity off, integrator implicitfast (the
actuator damping on the light J4 shaft is unstable under Euler), joint stiffness/damping unset, and
the actuator gains below are PLACEHOLDER numbers only good for moving sliders. The output stays
inside MuJoCo 3.12's MJCF (ros-jazzy-mujoco-vendor; tools/checks/mjcf_gate_312.sh): actuators are
written as `general` with explicit gain/bias, not set_to_position (4.0 writes input="pos").

Outputs: drone_line_sim/mjcf/line[.<name>][.dev].xml and its meshes under mjcf/meshes[/dev]/,
reports/gen_mjcf[.<name>][.dev].json. Without --dev the base spec's nulls stop the run (exit 1,
listed in the report). The MJCF is generated: edit the spec, never the XML.
"""

